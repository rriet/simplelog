/// Shared crew assignment draft.
class ImportedCrewAssignmentDraft {
  /// Creates a standard crew assignment.
  const ImportedCrewAssignmentDraft.crew({
    required this.position,
    required this.crew,
  }) : assignSelf = false,
       createSelfIfMissing = false;

  /// Creates an assignment for the current "self" crew member.
  const ImportedCrewAssignmentDraft.self({
    required this.position,
    required this.createSelfIfMissing,
  }) : crew = null,
       assignSelf = true;

  /// Assigned crew position.
  final CrewPosition position;

  /// Crew details when assigning a named crew member.
  final ImportedCrewDraft? crew;

  /// Whether the assignment targets the current self crew record.
  final bool assignSelf;

  /// Whether the self crew record may be created if missing.
  final bool createSelfIfMissing;
}

