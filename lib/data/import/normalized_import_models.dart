/// Shared overwrite configuration applied by the persistence service.
class ImportedEntityOptions {
  /// Creates entity overwrite options.
  const ImportedEntityOptions({
    required this.overrideAirportValues,
    required this.overrideAircraftValues,
    required this.overrideAircraftTypeValues,
    required this.overrideCrewValues,
  });

  /// Whether airport master data can be overwritten.
  final bool overrideAirportValues;

  /// Whether aircraft rows can be overwritten.
  final bool overrideAircraftValues;

  /// Whether aircraft type rows can be overwritten.
  final bool overrideAircraftTypeValues;

  /// Whether crew rows can be overwritten.
  final bool overrideCrewValues;

  /// Whether any imported entity can overwrite an existing row.
  bool get overrideExistingValues =>
      overrideAirportValues ||
      overrideAircraftValues ||
      overrideAircraftTypeValues ||
      overrideCrewValues;
}

/// Shared normalized payload consumed by the persistence service.
class NormalizedImportBatch {
  /// Creates a normalized import batch.
  const NormalizedImportBatch({
    required this.totalRows,
    required this.records,
    required this.entityOptions,
    this.skippedRows = 0,
    this.errorRows = 0,
  });

  /// Total source rows inspected by the parser.
  final int totalRows;

  /// Normalized records ready for persistence.
  final List<NormalizedImportRecord> records;

  /// Shared overwrite behavior for referenced entities.
  final ImportedEntityOptions entityOptions;

  /// Rows skipped during source parsing.
  final int skippedRows;

  /// Rows that failed while parsing.
  final int errorRows;
}

/// Base record generated by a source parser.
abstract class NormalizedImportRecord {
  /// Creates a normalized record.
  const NormalizedImportRecord(this.progressOrdinal);

  /// 1-based row progress used by the importer progress callback.
  final int progressOrdinal;
}

/// Shared airport draft used by normalized records.
class ImportedAirportDraft {
  /// Creates an airport draft.
  const ImportedAirportDraft({
    required this.icao,
    this.iata = '',
    this.name = '',
    this.city = '',
    this.country = '',
    this.latitude = 0,
    this.longitude = 0,
    this.latitudeRaw = '',
    this.longitudeRaw = '',
  });

  /// ICAO identifier.
  final String icao;

  /// IATA identifier.
  final String iata;

  /// Airport name.
  final String name;

  /// Airport city.
  final String city;

  /// Airport country.
  final String country;

  /// Latitude in decimal degrees.
  final double latitude;

  /// Longitude in decimal degrees.
  final double longitude;

  /// Original latitude text.
  final String latitudeRaw;

  /// Original longitude text.
  final String longitudeRaw;
}

